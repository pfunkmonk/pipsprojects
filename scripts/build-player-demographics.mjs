import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const defaultModel = "C:/Users/mailp/Dropbox/Personal/FAMILY STUFF/Mike Stuff/Fantasy Football/_AGENT_HANDOFF/data/player_season_vbd.csv";
const modelPath = resolve(process.argv[2] || defaultModel);
const packPath = resolve(process.argv[3] || `${root}/netlify/functions/_data/draft-pack-2026-provisional.json`);
const outputPath = resolve(process.argv[4] || `${root}/public/thunder-bowl/player-demographics-2026.mjs`);

function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = "";
  let quoted = false;
  for (let index = 0; index < text.length; index += 1) {
    const character = text[index];
    if (quoted) {
      if (character === '"' && text[index + 1] === '"') {
        field += '"';
        index += 1;
      } else if (character === '"') quoted = false;
      else field += character;
    } else if (character === '"') quoted = true;
    else if (character === ",") {
      row.push(field);
      field = "";
    } else if (character === "\n") {
      row.push(field.replace(/\r$/, ""));
      rows.push(row);
      row = [];
      field = "";
    } else field += character;
  }
  if (field || row.length) {
    row.push(field.replace(/\r$/, ""));
    rows.push(row);
  }
  const headers = rows.shift();
  return rows.filter((values) => values.some(Boolean)).map((values) => Object.fromEntries(headers.map((header, index) => [header, values[index] || ""])));
}

function normalizedName(value) {
  return String(value || "")
    .normalize("NFKD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/\b(?:jr|sr|ii|iii|iv)\b/g, " ")
    .replace(/[^a-z0-9]+/g, " ")
    .trim();
}

function playerKey(row) {
  return `${normalizedName(row.name)}|${String(row.pos || row.position).toUpperCase()}`;
}

function finiteInteger(value) {
  const number = Number(value);
  return Number.isInteger(number) && number >= 0 ? number : null;
}

const [modelCsv, packJson] = await Promise.all([readFile(modelPath, "utf8"), readFile(packPath, "utf8")]);
const modelRows = parseCsv(modelCsv);
const pack = JSON.parse(packJson);
const bySeason = new Map();
for (const season of [2025, 2026]) {
  const seasonRows = modelRows.filter((row) => Number(row.season) === season);
  const index = new Map();
  for (const row of seasonRows) {
    const key = playerKey(row);
    if (!index.has(key)) index.set(key, []);
    index.get(key).push(row);
  }
  bySeason.set(season, index);
}

function uniqueCandidate(rows, nflTeam) {
  if (!rows?.length) return null;
  if (rows.length === 1) return rows[0];
  const sameTeam = rows.filter((row) => String(row.team).toUpperCase() === String(nflTeam).toUpperCase());
  return sameTeam.length === 1 ? sameTeam[0] : null;
}

const demographics = {};
const audit = { establishedHistory: 0, currentOnly: 0, unknown: 0 };
for (const player of pack.players) {
  const key = playerKey(player);
  const established = uniqueCandidate(bySeason.get(2025).get(key), player.nflTeam);
  const current = uniqueCandidate(bySeason.get(2026).get(key), player.nflTeam);
  let age = null;
  let experience = null;
  let rookie = null;
  if (established) {
    const priorAge = finiteInteger(established.age);
    const priorExperience = finiteInteger(established.exp);
    age = priorAge === null ? null : priorAge + 1;
    experience = priorExperience === null ? null : priorExperience + 1;
    rookie = false;
    audit.establishedHistory += 1;
  } else if (current) {
    age = finiteInteger(current.age);
    experience = finiteInteger(current.exp);
    const draftYear = finiteInteger(current.draft_year);
    rookie = experience === 0 && draftYear === Number(pack.season);
    audit.currentOnly += 1;
  } else {
    audit.unknown += 1;
    continue;
  }
  demographics[player.id] = { age, experience, rookie };
}

const generatedAt = new Date().toISOString();
const output = `// Generated by scripts/build-player-demographics.mjs.\n// Display/filter metadata only: it has no projection, VBD, market, or bid-limit authority.\nexport const PLAYER_DEMOGRAPHICS_AUDIT = Object.freeze(${JSON.stringify({ generatedAt, source: "player_season_vbd.csv / nflverse identity fields", ...audit }, null, 2)});\n\nexport const PLAYER_DEMOGRAPHICS_2026 = Object.freeze(${JSON.stringify(demographics, null, 2)});\n`;
await writeFile(outputPath, output, "utf8");
console.log(JSON.stringify({ outputPath, players: pack.players.length, metadata: Object.keys(demographics).length, ...audit }, null, 2));
